# Builds the app's crest paths (src/components/brand/crest-paths.ts) and the icon set (public/icons) from the
# approved Club Crest geometry in concepts-2/gen.py. Run from this folder: python build_app_assets.py
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "concepts-2"))
os.chdir(os.path.join(HERE, "concepts-2"))
import gen  # noqa: E402  (writes the concept files as a side effect; harmless)
from gen import shield2, ball3, outline, f, BLUE, LIME, WHITE  # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
RENDER = r"C:/Users/MSI KATANA/.claude/plugins/cache/logo-design-skill/logo-design/1.4.4/skills/logo-design/scripts/render_png.py"
VIEWBOX = "32 4 192 242"


def centered(text, wght, size, track, cx, baseline):
    _, b = outline(text, wght, size, track, 0, 0)
    d, _ = outline(text, wght, size, track, cx - (b[2] - b[0]) / 2 - b[0], baseline)
    return d


def seam_paths(r):
    # ball3 returns two <path fill d=.../> when fill="none"; pull the d attributes out
    import re
    return re.findall(r' d="([^"]+)"', ball3(128, 34, r, fill="none"))


# Small cut for UI sizes (24-48px): a bigger ball in a wider notch so the lime still reads at 40px.
SMALL_R, SMALL_NOTCH, VIEWBOX_SMALL = 34, 42, "32 0 192 246"
shield_small = shield2(notch=SMALL_NOTCH)
seams_small = seam_paths(SMALL_R)


shield = shield2()
inner = shield2(10)
letters = centered("STC", 800, 66, 0, 128, 152)
letters_small = centered("STC", 800, 74, 0, 128, 156)
solo = centered("SOLO", 600, 16, 5, 130.5, 185)
_, sb = outline("SOLO", 600, 16, 5, 0, 0)
sw = sb[2] - sb[0] - 5
rules = f"M{f(128-sw/2-26)} 178.5H{f(128-sw/2-10)}M{f(128+sw/2+10)} 178.5H{f(128+sw/2+26)}"
seams = seam_paths(28)

ts = f'''// Generated by brand/logo/build_app_assets.py from the approved Club Crest. Do not edit by hand.
// The small cut for UI sizes: no inner line or SOLO, a bigger ball in a wider notch.
export const crestViewBox = '{VIEWBOX_SMALL}'
export const crestShield = '{shield_small}'
export const crestLetters = '{letters_small}'
export const crestBall = {{ cx: 128, cy: 34, r: {SMALL_R} }}
export const crestSeams = ['{seams_small[0]}', '{seams_small[1]}']
'''
with open(os.path.join(REPO, "src", "components", "brand", "crest-paths.ts"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write(ts)


def crest_svg(shield_fill, detail):
    parts = [f'<path fill="{shield_fill}" d="{shield}"/>']
    parts += [f'<path fill="none" stroke="{detail}" stroke-width="3.5" d="{inner}"/>',
              f'<path fill="{detail}" d="{letters}"/>', f'<path fill="{detail}" d="{solo}"/>',
              f'<path stroke="{detail}" stroke-width="2.5" stroke-linecap="round" d="{rules}"/>']
    parts.append(f'<circle cx="128" cy="34" r="28" fill="{LIME}"/>')
    parts += [f'<path fill="{WHITE}" d="{s}"/>' for s in seams]
    return "".join(parts)


def icon_on_tile(size, crest_height, radius):
    # crest (192x242 box) centred on a blue tile, optically nudged up 2%
    scale = crest_height / 242
    w = 192 * scale
    x = (size - w) / 2 - 32 * scale
    y = (size - crest_height) / 2 - 4 * scale - size * 0.01
    body = crest_svg(WHITE, BLUE)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}">'
            f'<rect width="{size}" height="{size}" rx="{radius}" fill="{BLUE}"/>'
            f'<g transform="translate({f(x)} {f(y)}) scale({f(scale)})">{body}</g></svg>')


icons = os.path.join(REPO, "public", "icons")
tmp = os.path.join(HERE, "concepts-2", "renders")
os.makedirs(tmp, exist_ok=True)

# Favicon: the small cut, transparent, with a blue rim on the ball so it holds on a light tab bar.
with open(os.path.join(icons, "icon.svg"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEWBOX_SMALL}"><title>Solo Tennis Club</title>'
             f'<path fill="{BLUE}" d="{shield_small}"/><path fill="{WHITE}" d="{letters_small}"/>'
             f'<circle cx="128" cy="34" r="{SMALL_R}" fill="{LIME}"/>'
             + "".join(f'<path fill="{WHITE}" d="{d}"/>' for d in seams_small)
             + f'<circle cx="128" cy="34" r="{SMALL_R - 3}" fill="none" stroke="{BLUE}" stroke-width="6"/></svg>')

jobs = [
    ("icon-192.png", 192, 0.72, 0.22),          # purpose any: rounded tile
    ("icon-512.png", 512, 0.72, 0.22),
    ("icon-maskable-512.png", 512, 0.58, 0),    # full bleed, crest inside the 80% safe zone
    ("apple-touch-icon.png", 180, 0.68, 0),     # iOS rounds the corners itself
]
for name, size, h, r in jobs:
    src = os.path.join(tmp, name.replace(".png", ".svg"))
    with open(src, "w", encoding="utf-8") as fh:
        fh.write(icon_on_tile(size, size * h, size * r))
    subprocess.run([sys.executable, RENDER, src, "-o", os.path.join(icons, name), "--size", str(size)], check=True)
print("crest paths and icons written")
